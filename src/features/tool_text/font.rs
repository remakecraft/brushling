/// Pixel size of a point size at 96 DPI (10 pt = 13 px).
pub fn px_for_pt(pt: u32) -> u32 {
    ((pt * 96 + 36) / 72).max(1)
}

/// Size-dependent layout numbers of the (fixed-pitch) bundled font.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Metrics {
    /// Glyph body (cap height) and width in pixels.
    pub gh: usize,
    pub gw: usize,
    /// Horizontal pitch of one character.
    pub adv: i32,
    /// Distance from the line top to the baseline.
    pub ascent: i32,
    /// Line height.
    pub lh: i32,
    bold: bool,
    /// Extra columns an italic glyph leans over.
    lean: usize,
}

impl Metrics {
    pub fn new(pt: u32, bold: bool, italic: bool) -> Metrics {
        let s = px_for_pt(pt) as f32;
        let k = s * 0.72 / 7.0;
        let gh = (7.0 * k).round().max(1.0) as usize;
        let gw = (5.0 * k).round().max(1.0) as usize;
        let gap = k.round().max(1.0) as i32;
        Metrics {
            gh,
            gw,
            adv: gw as i32 + gap + bold as i32,
            ascent: (s * 0.8).round() as i32,
            lh: s as i32,
            bold,
            lean: if italic { (gh / 4).max(1) } else { 0 },
        }
    }
}

/// A rendered glyph: `on[y * w + x]`, placed with its top-left at
/// (pen x, line top + ascent - gh).
pub struct Glyph {
    pub w: usize,
    pub h: usize,
    pub on: Vec<bool>,
}

fn overlap(a0: f32, a1: f32, b0: f32, b1: f32) -> f32 {
    (a1.min(b1) - a0.max(b0)).max(0.0)
}

pub fn glyph(ch: char, m: &Metrics) -> Glyph {
    let idx = match ch as u32 {
        c @ 32..=126 => (c - 32) as usize,
        _ => ('?' as u32 - 32) as usize,
    };
    let cols = &GLYPHS[idx];
    let sx = m.gw as f32 / 5.0;
    let sy = m.gh as f32 / 7.0;
    let ho = (8.0 * sy).ceil() as usize;
    let mut base = vec![false; m.gw * ho];
    for oy in 0..ho {
        let (y0, y1) = (oy as f32 / sy, (oy + 1) as f32 / sy);
        for ox in 0..m.gw {
            let (x0, x1) = (ox as f32 / sx, (ox + 1) as f32 / sx);
            let mut cov = 0.0;
            for (c, bits) in cols.iter().enumerate() {
                let wx = overlap(c as f32, c as f32 + 1.0, x0, x1);
                if wx == 0.0 {
                    continue;
                }
                for r in 0..8 {
                    if bits >> r & 1 == 1 {
                        cov += wx * overlap(r as f32, r as f32 + 1.0, y0, y1);
                    }
                }
            }
            base[oy * m.gw + ox] = cov / ((x1 - x0) * (y1 - y0)) >= 0.5 - 1e-4;
        }
    }
    let w = m.gw + m.bold as usize + m.lean;
    let mut on = vec![false; w * ho];
    for oy in 0..ho {
        // Italic: rows leaning right the further they sit above the baseline.
        let shift = if m.lean == 0 { 0 } else { (m.lean * m.gh.saturating_sub(oy)) / m.gh.max(1) };
        for ox in 0..m.gw {
            if base[oy * m.gw + ox] {
                on[oy * w + ox + shift] = true;
                if m.bold {
                    on[oy * w + ox + shift + 1] = true;
                }
            }
        }
    }
    Glyph { w, h: ho, on }
}
